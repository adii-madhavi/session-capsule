// continuation.md: the user's (or source agent's) note, followed by facts
// Session Capsule recorded itself. Missing sections are marked, never invented.

import { redactSecrets } from '../common/secrets.ts';
import { inertLine, mdFence, mdInlineCode } from '../common/sanitize.ts';
import type { CaptureMode, ConversationDoc, FilesIndex, GitInfo, HandoffObject } from '../common/types.ts';

export const NOTE_SECTIONS = ['Goal', 'Decisions', 'Completed work', 'Problems and open questions', 'Next steps'];

export function parseNote(md: string): Map<string, string> {
  const sections = new Map<string, string>();
  let current: string | null = null;
  for (const line of md.split(/\r?\n/)) {
    const h = line.match(/^##\s+(.+?)\s*$/);
    if (h) {
      current = NOTE_SECTIONS.find((s) => s.toLowerCase() === h[1].toLowerCase()) ?? h[1];
      sections.set(current, '');
    } else if (current) sections.set(current, `${sections.get(current)}${line}\n`);
  }
  for (const [k, v] of sections) sections.set(k, v.trim());
  return sections;
}

export function noteRequestPrompt(file = 'continuation-note.md'): string {
  return [
    'Write a continuation note so a fresh session on another computer can pick up this task without me explaining it again.',
    `Use exactly these Markdown headings: ${NOTE_SECTIONS.map((s) => `"## ${s}"`).join(', ')}.`,
    'Under "Completed work", list every command, migration, deployment, message or other external action you ran, and say whether you saw it succeed, fail, or don’t know. The next session will check those instead of repeating them.',
    'Say which files are finished and which are partly done. Do not include passwords, keys or tokens.',
    `Save it as ${file} in the project folder, then stop.`,
  ].join('\n');
}

export interface ContinuationInput {
  capsuleId: string;
  createdAt: string;
  mode: CaptureMode;
  sourceLabel: string;
  userNote: string | null;
  git: GitInfo | null;
  files: FilesIndex;
  conversation: ConversationDoc;
  handoff: HandoffObject | null;
}

const MISSING = '_Not recorded. Ask the user before assuming anything here._';

function section(title: string, items: unknown): string[] {
  const text = typeof items === 'string' ? items : JSON.stringify(items, null, 2);
  return [`### ${title}`, '', mdFence(redactSecrets(text).text, 'json'), ''];
}

export function buildContinuation(input: ContinuationInput): { markdown: string; missingSections: string[] } {
  const note = input.userNote ? parseNote(redactSecrets(input.userNote).text) : new Map<string, string>();
  const missingSections = NOTE_SECTIONS.filter((s) => !note.get(s));
  const out = [
    '# Continuation note',
    '',
    `Capsule \`${input.capsuleId}\` · created ${input.createdAt} · ${input.mode === 'full' ? 'full capsule (context and project files)' : 'context only (files moved separately)'}`,
    `Source: ${inertLine(input.sourceLabel)}`,
    '',
    '> This is a handoff from another computer, not a restored session. A note or summary does not preserve every detail of the original conversation. When this note and the project files disagree, trust the files and ask the user.',
    '',
  ];
  for (const s of NOTE_SECTIONS) out.push(`## ${s}`, '', note.get(s) || MISSING, '');
  for (const [k, v] of note) if (!NOTE_SECTIONS.includes(k) && v) out.push(`## ${k}`, '', v, '');

  out.push('## Recorded facts (generated by Session Capsule)', '');
  out.push('### Project state at capture', '');
  if (input.git) {
    out.push(`- Git: branch ${input.git.branch ? mdInlineCode(input.git.branch) : '(detached)'} at ${input.git.head ? mdInlineCode(input.git.head.slice(0, 12)) : '(no commits)'}; uncommitted changes: ${input.git.dirty ? 'yes' : 'no'}`);
  } else out.push('- Not a git repository; no base versions or deletions were recorded.');
  const changed = input.files.entries.filter((f) => f.status !== 'unchanged' && f.status !== 'unknown');
  const marks: Record<string, string> = { modified: 'M', added: 'A', untracked: '?' };
  if (changed.length || input.files.deletions.length) {
    out.push(`- Changed since the last commit (${changed.length + input.files.deletions.length}):`);
    for (const f of changed.slice(0, 60)) out.push(`  - ${marks[f.status]} ${mdInlineCode(f.path)}`);
    for (const d of input.files.deletions.slice(0, 20)) out.push(`  - D ${mdInlineCode(d.path)}`);
    if (changed.length > 60) out.push(`  - … ${changed.length - 60} more`);
  }
  out.push('');

  const actions = input.conversation.messages.filter((m) => m.action);
  out.push('### Actions recorded in the conversation', '');
  if (actions.length) {
    out.push('Check the project before repeating any of these. Commands, migrations and external actions may already have run, and a recorded result is not proof of success.', '');
    for (const m of actions.slice(-40)) out.push(`- ${m.action?.type}: ${mdInlineCode(m.action?.summary ?? '')}`);
    if (actions.length > 40) out.push(`- … ${actions.length - 40} earlier actions are in conversation.md`);
  } else out.push('_None recorded._');
  out.push('');

  const lastUser = input.conversation.messages.findLast((m) => m.role === 'user');
  if (lastUser) out.push('### Last request from the user', '', mdFence(lastUser.text.slice(0, 2000)), '');

  const h = input.handoff;
  if (h?.checkpoint) {
    out.push('## Recorder checkpoint (Blocker / desktop-continuity)', '');
    out.push('These sections are copied from the recorder, with its labels. Observed facts were recorded as they happened. Agent notes are claims by the source agent. Inferences were derived from files and are not intent.', '');
    out.push(...section('Observed (recorded as it happened)', h.checkpoint.observed));
    out.push(...section('Agent notes (claims, not verified)', h.checkpoint.agentNotes));
    out.push(...section('Inferred remaining work (confirm before relying on it)', h.checkpoint.inferred));
    out.push('### Missing or unknown', '', ...h.checkpoint.missing.map((m) => `- ${inertLine(m, 500)}`), '');
  }
  if (h?.sourceStatusAtCapture) {
    out.push('## Source status at capture (historical)', '');
    out.push(`Observed on the source computer at ${h.sourceStatusAtCapture.observedAt}. It is not a live check, and nothing here can tell whether the source computer is working now.${h.sourceStatusAtCapture.exportForced ? ' **The export was forced while the source may still have been working.**' : ''}`, '');
    out.push(...section('Status', h.sourceStatusAtCapture.status));
  }
  return { markdown: out.join('\n'), missingSections };
}
